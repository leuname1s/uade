
-- 1. Artistas
CREATE TABLE artistas (
codArtista INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
nombre VARCHAR(200) NOT NULL,
CONSTRAINT pk_artistas PRIMARY KEY (codArtista)
);

-- 2. Géneros
CREATE TABLE generos (
codGenero INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
descripcion VARCHAR(200) NOT NULL,
CONSTRAINT pk_generos PRIMARY KEY (codGenero)
);

-- 3. Álbumes
CREATE TABLE albumes (
codAlbum INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
titulo VARCHAR(200) NOT NULL,
fecha DATE,
codArtista INT,
codGenero INT,
CONSTRAINT pk_albumes PRIMARY KEY (codAlbum),
CONSTRAINT fk_albumes_artistas FOREIGN KEY (codArtista) REFERENCES artistas (codArtista) ON DELETE SET NULL,
CONSTRAINT fk_albumes_generos FOREIGN KEY (codGenero) REFERENCES generos (codGenero) ON DELETE SET NULL
);

-- 4. Temas
CREATE TABLE temas (
codTema INT GENERATED BY DEFAULT AS IDENTITY,
titulo VARCHAR(200) NOT NULL,
orden INT,
duracion INT, -- Duración en segundos
codAlbum INT,
CONSTRAINT pk_temas PRIMARY KEY (codTema),
CONSTRAINT fk_temas_albumes FOREIGN KEY (codAlbum) REFERENCES albumes (codAlbum) ON DELETE CASCADE
);

-- 5. Clientes
CREATE TABLE clientes (
codCliente INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
nombre VARCHAR(200) NOT NULL,
saldo NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
CONSTRAINT pk_clientes PRIMARY KEY (codCliente)
);

-- 6. Pedidos
CREATE TABLE pedidos (
nroPedido INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
fecha DATE NOT NULL DEFAULT CURRENT_DATE,
codCliente INT,
fechaEntrega DATE,
lugarEntrega VARCHAR(300),
CONSTRAINT pk_pedidos PRIMARY KEY (nroPedido),
CONSTRAINT fk_pedidos_clientes FOREIGN KEY (codCliente) REFERENCES clientes (codCliente) ON DELETE RESTRICT
);

-- 7. Facturas
CREATE TABLE facturas (
nroFactura INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
fecha DATE NOT NULL DEFAULT CURRENT_DATE,
codCliente INT,
codPedido INT,
bruto NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
iva NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
iibb NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
final NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
anulada BOOLEAN NOT NULL DEFAULT FALSE, --Para trigger Parte C
usuarioAnulacion VARCHAR(100), --Para trigger Parte C
CONSTRAINT pk_facturas PRIMARY KEY (nroFactura),
CONSTRAINT fk_facturas_clientes FOREIGN KEY (codCliente) REFERENCES clientes (codCliente) ON DELETE RESTRICT,
CONSTRAINT fk_facturas_pedidos FOREIGN KEY (codPedido) REFERENCES pedidos (nroPedido) ON DELETE SET NULL
);

-- 8. Productos
CREATE TABLE productos (
codProducto INT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
descripcion VARCHAR(300) NOT NULL,
stock INT NOT NULL DEFAULT 0,
puntoReposicion INT NOT NULL DEFAULT 0,
precio NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
CONSTRAINT pk_productos PRIMARY KEY (codProducto),
CONSTRAINT chk_stock_positivo CHECK (stock >= 0),
CONSTRAINT chk_precio_positivo CHECK (precio >= 0)
);

-- 9. ItemsPedido
CREATE TABLE itemsPedido (
codProducto INT NOT NULL,
nroPedido INT NOT NULL,
cantidad INT NOT NULL,
CONSTRAINT pk_itemspedido PRIMARY KEY (codProducto, nroPedido),
CONSTRAINT fk_itemspedido_productos FOREIGN KEY (codProducto) REFERENCES productos (codProducto) ON DELETE RESTRICT,
CONSTRAINT fk_itemspedido_pedidos FOREIGN KEY (nroPedido) REFERENCES pedidos (nroPedido) ON DELETE CASCADE,
CONSTRAINT chk_itemspedido_cantidad CHECK (cantidad > 0)
);

-- 10. ItemsFactura
CREATE TABLE itemsFactura (
codProducto INT NOT NULL,
nroFactura INT NOT NULL,
cantidad INT NOT NULL,
precio NUMERIC(12, 2) NOT NULL,
descuento NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
CONSTRAINT pk_itemsfactura PRIMARY KEY (codProducto, nroFactura),
CONSTRAINT fk_itemsfactura_productos FOREIGN KEY (codProducto) REFERENCES productos (codProducto) ON DELETE RESTRICT,
CONSTRAINT fk_itemsfactura_facturas FOREIGN KEY (nroFactura) REFERENCES facturas (nroFactura) ON DELETE CASCADE,
CONSTRAINT chk_itemsfactura_cantidad CHECK (cantidad > 0),
CONSTRAINT chk_itemsfactura_precio CHECK (precio >= 0)
);

-- 11. Composiciones
CREATE TABLE composiciones (
codProducto INT NOT NULL,
codProductoComponente INT NOT NULL,
cantidad INT NOT NULL,
CONSTRAINT pk_composiciones PRIMARY KEY (codProducto, codProductoComponente),
CONSTRAINT fk_composiciones_producto FOREIGN KEY (codProducto) REFERENCES productos (codProducto) ON DELETE CASCADE,
CONSTRAINT fk_composiciones_componente FOREIGN KEY (codProductoComponente) REFERENCES productos (codProducto) ON DELETE RESTRICT,
CONSTRAINT chk_composiciones_cantidad CHECK (cantidad > 0),
CONSTRAINT chk_distintos_productos CHECK (codProducto <> codProductoComponente)
);

-- 12. Usuarios
CREATE TABLE usuarios (
idUsuario INT GENERATED BY DEFAULT AS IDENTITY,
nombre VARCHAR(200) NOT NULL,
alias VARCHAR(50) NOT NULL,
contrasena VARCHAR(255) NOT NULL,
activo BOOLEAN NOT NULL DEFAULT TRUE,
email VARCHAR(250) NOT NULL,
CONSTRAINT pk_usuarios PRIMARY KEY (idUsuario),
CONSTRAINT unq_usuarios_alias UNIQUE (alias),
CONSTRAINT unq_usuarios_email UNIQUE (email)
);

-- 13. Categorías
CREATE TABLE categorias (
idCategoria INT GENERATED BY DEFAULT AS IDENTITY,
nombre VARCHAR(100) NOT NULL,
descripcion VARCHAR(500),
CONSTRAINT pk_categorias PRIMARY KEY (idCategoria)
);

-- 14. Noticias
CREATE TABLE noticias (
idNoticia INT GENERATED BY DEFAULT AS IDENTITY,
titulo VARCHAR(250) NOT NULL,
idCategoria INT,
idAutor INT,
fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
ubicacion VARCHAR(500) NOT NULL,
CONSTRAINT pk_noticias PRIMARY KEY (idNoticia),
CONSTRAINT fk_noticias_categorias FOREIGN KEY (idCategoria) REFERENCES categorias (idCategoria) ON DELETE SET NULL,
CONSTRAINT fk_noticias_usuarios FOREIGN KEY (idAutor) REFERENCES usuarios (idUsuario) ON DELETE SET NULL
);

-- 15. Comentarios
CREATE TABLE comentarios (
idComentario INT GENERATED BY DEFAULT AS IDENTITY,
idNoticia INT NOT NULL,
texto TEXT NOT NULL,
idUsuario INT,
fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
CONSTRAINT pk_comentarios PRIMARY KEY (idComentario),
CONSTRAINT fk_comentarios_noticias FOREIGN KEY (idNoticia) REFERENCES noticias (idNoticia) ON DELETE CASCADE,
CONSTRAINT fk_comentarios_usuarios FOREIGN KEY (idUsuario) REFERENCES usuarios (idUsuario) ON DELETE SET NULL
);

-- 16. Privilegios
CREATE TABLE privilegios (
idUsuario INT NOT NULL,
privilegio VARCHAR(50) NOT NULL,
idCategoria INT NOT NULL,
CONSTRAINT pk_privilegios PRIMARY KEY (idUsuario, privilegio, idCategoria),
CONSTRAINT fk_privilegios_usuarios FOREIGN KEY (idUsuario) REFERENCES usuarios (idUsuario) ON DELETE CASCADE,
CONSTRAINT fk_privilegios_categorias FOREIGN KEY (idCategoria) REFERENCES categorias (idCategoria) ON DELETE CASCADE,
CONSTRAINT chk_privilegio_valido CHECK (privilegio IN ('Crear Noticia', 'Responsable'))
);

-- 17. Votaciones
CREATE TABLE votaciones (
idVotacion INT GENERATED BY DEFAULT AS IDENTITY,
idNoticia INT NOT NULL,
fechaInicio TIMESTAMP NOT NULL,
fechaFin TIMESTAMP NOT NULL,
pregunta TEXT NOT NULL,
respuesta1 VARCHAR(250) NOT NULL,
respuesta2 VARCHAR(250) NOT NULL,
respuesta3 VARCHAR(250) NOT NULL,
votosOp1 INT NOT NULL DEFAULT 0,
votosOp2 INT NOT NULL DEFAULT 0,
votosOp3 INT NOT NULL DEFAULT 0,
CONSTRAINT pk_votaciones PRIMARY KEY (idVotacion),
CONSTRAINT fk_votaciones_noticias FOREIGN KEY (idNoticia) REFERENCES noticias (idNoticia) ON DELETE CASCADE,
CONSTRAINT chk_fechas_votacion CHECK (fechaFin > fechaInicio),
CONSTRAINT chk_votos1_positivo CHECK (votosOp1 >= 0),
CONSTRAINT chk_votos2_positivo CHECK (votosOp2 >= 0),
CONSTRAINT chk_votos3_positivo CHECK (votosOp3 >= 0)
);

-- Logs para Parte C
CREATE TABLE logs (
    idLog INT GENERATED BY DEFAULT AS IDENTITY,
    operacion VARCHAR(20) NOT NULL,
    nroPedido INT,
    nroFactura INT NOT NULL,
    fechaHora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    usuario VARCHAR(100) NOT NULL DEFAULT CURRENT_USER,
    filasInvolucradas INT NOT NULL DEFAULT 0,
    CONSTRAINT pk_logs PRIMARY KEY (idLog),
    -- Regla de integridad CHECK
    CONSTRAINT chk_logs_operacion CHECK (operacion IN ('FACTURACION', 'ANULACION'))
);